let numero1 = parseFloat(prompt("Digite o primeiro número: "));
let numero2 = parseFloat(prompt("Digite o segundo número: "));

alert("Soma dos números: " + (numero1 + numero2));
alert("Subtração do primeiro pelo segundo: " + (numero2-numero1));
alert("Produto dos números: " + (numero1*numero2));
alert("Divisão do primeiro pelo segundo: " + (numero1/numero2));
alert("Resto da divisão: " + (numero1%numero2));